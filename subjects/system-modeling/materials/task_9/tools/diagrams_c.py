# ------------------------------------------------------------------------------------ 10. object diagram

def obj(c, x, y, w, title, rows, fill="#ffffff"):
    lines = [r for r in rows]
    h1 = 22
    head = c.rect(x, y, w, h1, title, underline=True, bold=True, size=10, fill="#e1d5e7", pad=3)
    n = sum(len(wrap_lines(r, w - 10, 10)) for r in lines)
    body = c.rect(x, y + h1, w, 12.5 * n + 8, "\n".join(lines), align="left", valign="top", size=10, pad=5, fill=fill)
    from diagram_lib import Shape
    return Shape(head.id, x, y, w, h1 + body.h)


